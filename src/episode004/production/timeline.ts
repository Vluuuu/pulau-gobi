export const DURATION=cursor;
export const SLOTS=slots;
export const voiceSlot=(id:number)=>slots.find(s=>s.voice===id)!;
export const atVoice=(id:number)=>voiceSlot(id).start;
export const clamp=(v:number)=>Math.max(0,Math.min(1,v));
export const smooth=(v:number)=>{const t=clamp(v);return t*t*(3-2*t);};
export const ramp=(f:number,a:number,b:number)=>smooth((f-a)/(b-a));
export const lerp=(a:number,b:number,t:number)=>a+(b-a)*t;
export const pulse=(f:number,a:number,b:number)=>f<a||f>b?0:Math.sin(Math.PI*(f-a)/(b-a));
export const span=(f:number,a:number,b:number,r=6)=>ramp(f,a,a+r)*(1-ramp(f,b-r,b));
export const active=(s:Slot,f:number)=>f>=s.start&&f<s.end;
export const localWord=(id:number,text:string,last=false)=>{const a=VO[id-1].words.filter(w=>w.text.toLowerCase().includes(text.toLowerCase()));return Math.round((last?a[a.length-1]:a[0])?.start! *30)||0;};
export const progressAt=(f:number,a:Slot,b:Slot=a)=>clamp((f-a.start)/(b.end-a.start));
export function buildsAt(f:number){return {green:progressAt(f,GREEN_A,GREEN_B),expansion:ramp(f,GREEN_B.start+6,GREEN_B.start+55),farm:progressAt(f,FARM_A,FARM_B),ranch:progressAt(f,RANCH_A,RANCH_B),kost:progressAt(f,KOST_A,KOST_C)};}
export const radiusAt=(f:number)=>lerp(37.5,52,buildsAt(f).expansion);
export const inComedy=(f:number)=>active(COMEDY,f);
